#!/usr/bin/env python3
"""Regenerate the README front-page table from bench/results.jsonl.

One row per (gfx target, model): the engine runs more than one model and their
frame times differ by well over half, so a row that pooled them would be a
number from nowhere. Within a row, the latest git hash that has results for
that pair is the release, and the row shows the median over that hash's runs
(ms/frame, vocoder, TTFA, RTF) and the hash. Targets without results keep
their dashes. Runs with a "-dirty" hash are ignored (bench/README.md).

Only the standard protocol is included: the bench voice (voice_1.wav) and
embedding-only cloning. In-context rows measure a different thing - their
prompt carries a reference clip's frames, and their utterance length depends
on which clip - so pooling them in here would mix two measurements. They are
compared in docs/tuning.md instead.

    uv run tools/bench_table.py            # rewrites README.md in place
    uv run tools/bench_table.py --check    # exit 1 if README.md is stale
"""

import json
import re
import statistics
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TARGETS = {
    "gfx1100": ("Workstation", "Radeon RX 7900 XTX (gfx1100, 96 CU)"),
    "gfx1151": ("Mini PC", "Strix Halo (gfx1151, 40 CU)"),
}
BEGIN, END = "| Target |", "*(Generated by"


# "Qwen3-TTS-12Hz-0.6B-Base" -> "0.6B"; anything unexpected keeps its own name.
def model_label(name):
    m = re.search(r"(\d+\.?\d*B)", name or "")
    return m.group(1) if m else (name or "?")


def rows():
    path = ROOT / "bench" / "results.jsonl"
    runs = [json.loads(l) for l in path.read_text().splitlines() if l.strip()] if path.exists() else []
    runs = [r for r in runs if not r["git"].endswith("-dirty") and r.get("rtf") is not None]
    # the standard protocol only (see the module docstring); rows from before the `voice`
    # field was recorded are all the bench voice, embedding-only
    runs = [r for r in runs if r.get("clone_mode") is None and r.get("voice", "voice_1.wav") == "voice_1.wav"]
    out = ["| Target | GPU | Model | ROCm | ms/frame | Vocoder | TTFA | RTF | Build |",
           "|---|---|---|---|---|---|---|---|---|"]
    for gfx, (name, gpu) in TARGETS.items():
        mine = [r for r in runs if r["gfx"] == gfx]
        if not mine:
            out.append(f"| {name} | {gpu} | — | — | — | — | — | — | — |")
            continue
        # smallest model first, which is the order the engine grew them in
        for model in sorted({r["model"] for r in mine}, key=lambda m: (model_label(m), m)):
            theirs = [r for r in mine if r["model"] == model]
            latest = theirs[-1]["git"]
            sel = [r for r in theirs if r["git"] == latest]
            med = lambda k: statistics.median(r[k] for r in sel)
            rocm = f"≥ 10.1 (built with {latest_rocm(sel)})"
            out.append(f"| {name} | {gpu} | {model_label(model)} | {rocm} | {med('frame_ms'):.2f} ms "
                       f"| {med('vocoder_ms_per_frame'):.2f} ms/frame | {med('ttfa_ms'):.0f} ms "
                       f"| {med('rtf'):.3f} | `{latest[:7]}` ×{len(sel)} |")
    return "\n".join(out)


def latest_rocm(sel):
    return sel[-1]["rocm"]


def main():
    readme = ROOT / "README.md"
    text = readme.read_text()
    start = text.index(BEGIN)
    end = text.index(END, start)
    new = text[:start] + rows() + "\n\n" + text[end:]
    if "--check" in sys.argv:
        sys.exit(0 if new == text else 1)
    readme.write_text(new)
    print(rows())


if __name__ == "__main__":
    main()
